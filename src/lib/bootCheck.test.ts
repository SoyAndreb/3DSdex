import { describe, expect, it } from 'vitest';
import { createCompatRootFromFiles } from './compatFs.ts';
import {
  evaluateLumaConfig,
  inspectBootLayout,
  parseLumaConfig,
} from './bootCheck.ts';

/** All fixtures are defined here; no repository reference folders are read. */
function fakeFile(relPath: string, content: string, lastModified = 1700000000000): File {
  const name = relPath.split('/').pop() ?? relPath;
  const file = new File([content], name, { lastModified });
  Object.defineProperty(file, 'webkitRelativePath', { value: relPath });
  return file;
}

const SANE_CONFIG = `
; generated by Luma3DS
[meta]
config_version_major = 3
config_version_minor = 16
[boot]
autoboot_emunand = 0
autoboot_mode = off
app_launch_new_3ds_cpu = off
pin_lock_num_digits = 0
enable_game_patching = 1
enable_external_firm_and_modules = 1
use_dev_unitinfo = 0
`;

describe('parseLumaConfig', () => {
  it('reads sections and keys, ignoring comments and duplicates', () => {
    const parsed = parseLumaConfig(SANE_CONFIG);
    expect(parsed.sections.has('meta')).toBe(true);
    expect(parsed.values.get('meta.config_version_minor')).toBe('16');
    expect(parsed.values.get('boot.autoboot_emunand')).toBe('0');
    expect(evaluateLumaConfig(parsed)).toEqual([]);
  });

  it('reports missing metadata and unusual boot options without changing anything', () => {
    const parsed = parseLumaConfig(
      '[boot]\nautoboot_emunand = 1\nautoboot_mode = emunand\npin_lock_num_digits = 4\nenable_game_patching = 0\nuse_dev_unitinfo = 1\n',
    );
    expect(evaluateLumaConfig(parsed).map((f) => f.code)).toEqual([
      'missing-meta',
      'autoboot-emunand',
      'autoboot-mode',
      'pin-lock',
      'dev-unitinfo',
      'game-patching-off',
    ]);
  });
});

describe('inspectBootLayout', () => {
  it('reports boot files, payload duplicates and Luma config findings', async () => {
    const compat = createCompatRootFromFiles([
      fakeFile('SD/boot.firm', 'firm-bytes'),
      fakeFile('SD/boot.3dsx', 'hbmenu-bytes'),
      fakeFile('SD/luma/config.ini', '[meta]\nconfig_version_major = 3\nconfig_version_minor = 16\n[boot]\nautoboot_emunand = 1\n'),
      fakeFile('SD/luma/payloads/GodMode9.firm', 'payload-one'),
      fakeFile('SD/luma/payloads/godmode9 (1).firm', 'payload-two'),
      fakeFile('SD/Nintendo 3DS/00000000/secret.dat', 'private'),
    ]);

    const result = await inspectBootLayout(compat.handle);
    expect(result.bootFirm.present).toBe(true);
    expect(result.bootFirm.size).toBe('firm-bytes'.length);
    expect(result.boot3dsx.present).toBe(true);
    expect(result.payloads).toHaveLength(2);
    expect(result.duplicatePayloads).toBe(1);
    expect(result.outdatedPayloads).toBe(0);
    expect(result.lumaConfig.status).toBe('present');
    expect(result.lumaConfig.version).toBe('16');
    expect(result.lumaConfig.findings.map((f) => f.code)).toContain('autoboot-emunand');
  });

  it('reports a missing Luma config and an empty payload folder', async () => {
    const compat = createCompatRootFromFiles([fakeFile('SD/boot.firm', 'firm')]);
    const result = await inspectBootLayout(compat.handle);
    expect(result.boot3dsx.present).toBe(false);
    expect(result.payloads).toEqual([]);
    expect(result.lumaConfig.status).toBe('missing');
    expect(result.outdatedPayloads).toBe(0);
  });
});
